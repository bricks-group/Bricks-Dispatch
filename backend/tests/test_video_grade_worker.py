"""
Tests for the standalone video_worker/grade.py module (2026-09-12).

This module is NOT wired into the live post-production pipeline (see its own
module docstring and CLAUDE.md's "Motion (Video) Enhancement -- Researched,
Not Deployed" section for why) -- these tests exercise it in isolation,
against a tiny synthetic ffmpeg-generated test-pattern video, the same
"synthetic input, not a real fixture" convention test_photo_enhance_service.py
uses for images.

Every test that actually shells out to ffmpeg is skipped when ffmpeg/ffprobe
aren't on PATH, so this file collects and passes cleanly in an environment
without ffmpeg installed (this sandbox didn't have it until installed for
this session; CI's ubuntu-latest runner ships ffmpeg preinstalled, so there
these run for real, not just skip).
"""
import os
import subprocess
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from video_worker.grade import (  # noqa: E402
    VideoGradeError,
    build_grade_filtergraph,
    ffmpeg_available,
    probe_duration_seconds,
    process_video,
    stabilization_available,
    trim_only,
)

requires_ffmpeg = pytest.mark.skipif(
    not ffmpeg_available(),
    reason="ffmpeg/ffprobe not on PATH -- video_worker tests need a real binary, not a stub",
)


@pytest.fixture()
def testsrc_video(tmp_path):
    """A tiny synthetic 3-second test-pattern video with a silent audio
    track, generated by ffmpeg's own lavfi testsrc -- no external fixture
    file needed, mirrors test_photo_enhance_service.py's synthetic-input
    convention for images."""
    path = str(tmp_path / "testsrc.mp4")
    subprocess.run(
        [
            "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", "testsrc=size=320x240:rate=24:duration=3",
            "-f", "lavfi", "-i", "anullsrc=r=44100:cl=stereo",
            "-shortest",
            path,
        ],
        check=True,
    )
    return path


class TestFeatureDetection:
    @requires_ffmpeg
    def test_build_grade_filtergraph_uses_clahe_when_available(self):
        graph = build_grade_filtergraph(frozenset({"clahe", "colorbalance", "eq", "unsharp"}))
        assert graph.startswith("clahe=")

    @requires_ffmpeg
    def test_build_grade_filtergraph_falls_back_to_histeq_without_clahe(self):
        graph = build_grade_filtergraph(frozenset({"colorbalance", "eq", "unsharp"}))
        assert graph.startswith("histeq=")
        assert "clahe" not in graph

    @requires_ffmpeg
    def test_filtergraph_always_includes_colorbalance_eq_and_unsharp(self):
        graph = build_grade_filtergraph(frozenset())
        assert "colorbalance=" in graph
        assert "eq=" in graph
        assert "unsharp=" in graph


class TestProcessVideo:
    @requires_ffmpeg
    def test_grades_without_stabilize_or_trim(self, testsrc_video, tmp_path):
        out = str(tmp_path / "graded.mp4")
        result = process_video(testsrc_video, out)

        assert os.path.exists(out)
        assert os.path.getsize(out) > 0
        assert result.graded is True
        assert result.stabilized is False
        assert result.trimmed is False
        assert result.source_duration_s == pytest.approx(3.0, abs=0.2)
        assert result.output_duration_s == pytest.approx(3.0, abs=0.2)
        assert result.warnings == []

    @requires_ffmpeg
    def test_trims_to_max_duration(self, testsrc_video, tmp_path):
        out = str(tmp_path / "trimmed.mp4")
        result = process_video(testsrc_video, out, max_duration_s=1.0)

        assert result.trimmed is True
        assert result.output_duration_s == pytest.approx(1.0, abs=0.2)

    @requires_ffmpeg
    def test_no_trim_flag_when_source_shorter_than_requested_max(self, testsrc_video, tmp_path):
        out = str(tmp_path / "not_trimmed.mp4")
        # Source is 3s; requesting a 10s cap should not be reported as a trim.
        result = process_video(testsrc_video, out, max_duration_s=10.0)

        assert result.trimmed is False
        assert result.output_duration_s == pytest.approx(3.0, abs=0.2)

    @requires_ffmpeg
    def test_stabilize_true_sets_stabilized_flag_when_vidstab_available(self, testsrc_video, tmp_path):
        out = str(tmp_path / "stabilized.mp4")
        result = process_video(testsrc_video, out, stabilize=True)

        if stabilization_available():
            assert result.stabilized is True
            assert result.warnings == []
        else:
            # Degrades gracefully -- graded output still produced, with a
            # warning explaining why stabilization was skipped, never an
            # exception, on an ffmpeg build without libvidstab.
            assert result.stabilized is False
            assert any("vidstab" in w for w in result.warnings)
        assert os.path.exists(out)
        assert os.path.getsize(out) > 0

    @requires_ffmpeg
    def test_missing_input_raises_video_grade_error(self, tmp_path):
        with pytest.raises(VideoGradeError):
            process_video(str(tmp_path / "does_not_exist.mp4"), str(tmp_path / "out.mp4"))

    def test_raises_clear_error_when_ffmpeg_unavailable(self, tmp_path, monkeypatch):
        monkeypatch.setattr("video_worker.grade.ffmpeg_available", lambda: False)
        with pytest.raises(VideoGradeError, match="ffmpeg"):
            process_video(str(tmp_path / "in.mp4"), str(tmp_path / "out.mp4"))


class TestTrimOnly:
    @requires_ffmpeg
    def test_trim_only_is_lossless_stream_copy(self, testsrc_video, tmp_path):
        out = str(tmp_path / "trim_only.mp4")
        trim_only(testsrc_video, out, 1.0)

        assert os.path.exists(out)
        duration = probe_duration_seconds(out)
        assert duration == pytest.approx(1.0, abs=0.2)

    def test_trim_only_raises_when_ffmpeg_unavailable(self, tmp_path, monkeypatch):
        monkeypatch.setattr("video_worker.grade.ffmpeg_available", lambda: False)
        with pytest.raises(VideoGradeError):
            trim_only(str(tmp_path / "in.mp4"), str(tmp_path / "out.mp4"), 1.0)


class TestProbeDuration:
    @requires_ffmpeg
    def test_probe_duration_on_real_file(self, testsrc_video):
        duration = probe_duration_seconds(testsrc_video)
        assert duration == pytest.approx(3.0, abs=0.2)

    @requires_ffmpeg
    def test_probe_duration_on_missing_file_returns_none(self, tmp_path):
        assert probe_duration_seconds(str(tmp_path / "nope.mp4")) is None
